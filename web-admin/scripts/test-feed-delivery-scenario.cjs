const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const mod = { exports: {} };
new Function('exports', ts.transpileModule(fs.readFileSync(path.join(__dirname, '../lib/feed-delivery-scenario.ts'), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText)(mod.exports);
const project = mod.exports.projectFeedDeliveries;
const daily = [23,24,25,26,27,28].map(day => ({ date: `2026-09-${day}`, starter: 0, grower: 5280 }));
const order = { id: 'request', date: '2026-09-25', pounds: 18000, feedType: 'grower', included: true };
assert.equal(project(0,11404,daily,[]).firstShortfall,'2026-09-25');
let result = project(0,11404,daily,[order]);
assert.equal(result.firstShortfall,'2026-09-28');
assert.equal(result.days[0].arriving,0, 'No credit before delivery');
assert.equal(result.days[2].arriving,18000);
result = project(0,11404,daily,[{...order,date:'2026-09-27'}]);
assert.equal(result.firstShortfall,'2026-09-25', 'Late delivery cannot erase earlier shortfall');
assert.ok(result.days[2].shortfall > 0);
assert.equal(result.days[4].shortfall,0);
assert.equal(project(0,11404,daily,[{...order,included:false}]).totalShortfall,project(0,11404,daily,[]).totalShortfall);
assert.equal(project(0,11404,daily,[order,{...order,id:'second',date:'2026-09-28',pounds:5000}]).firstShortfall,null);
assert.equal(project(0,11404,daily,[{...order,date:'2026-10-01'}]).totalShortfall,project(0,11404,daily,[]).totalShortfall);
assert.ok(project(0,11404,daily,[{...order,date:''}]).error);
assert.ok(project(0,11404,daily,[{...order,date:'2026-09-22'}]).error);
assert.ok(project(0,11404,daily,[{...order,pounds:NaN}]).error);
assert.ok(project(0,11404,daily,[{...order,feedType:''}]).error);
assert.ok(project(null,11404,daily,[]).error);
assert.ok(project(0,11404,[{date:'2026-09-23',starter:null,grower:null}],[]).error);
assert.equal(project(0,100,[{date:'2026-09-23',starter:50,grower:0}],[]).totalShortfall,50, 'Grower does not replace starter');
assert.equal(project(100,0,[{date:'2026-09-23',starter:20,grower:50}],[]).days[0].balance,30);
console.log('Delivery scenario tests passed: timing, late gaps, exclusion, multiple deliveries, feed types and missing inputs.');
