const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const source = fs.readFileSync(path.join(__dirname, '../lib/feed-projection-report-data.ts'), 'utf8') + '\nexport { buildFeedProjection };';
const mod = { exports: {} };
new Function('require', 'exports', ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText)(() => ({}), mod.exports);
const build = mod.exports.buildFeedProjection;
const input = { today: '2026-09-22', windowDays: 2, ageDays: 7, currentFemaleCount: 5000, currentMaleCount: 5000, projectedFemaleMortalityPerDay: 0, projectedMaleMortalityPerDay: 0, breedFemales: null, breedMales: null, breedById: new Map(), breedSpecRows: [], liveHaulEvents: [] };
let result = build(input);
assert.equal(result.total, null);
assert.equal(result.problems.length, 2);
assert.ok(result.problems.some(p => p.includes('Female breed is missing')));
assert.ok(result.problems.some(p => p.includes('Male breed is missing')));
const configured = { ...input, breedFemales: 'f', breedById: new Map([['f', { breed_name: 'Example', sex: 'female' }]]), breedSpecRows: [8,9].map(age => ({ geneticname: 'Example', breedid: 'female', age, dayfeedperbird: 0.1 })) };
result = build(configured);
assert.equal(result.total, null, 'Must not silently omit male consumption');
assert.equal(result.problems.length, 1);
result = build({ ...configured, currentMaleCount: 0 });
assert.equal(result.total, 1000);
assert.deepEqual(result.problems, []);
result = build({ ...configured, currentMaleCount: 0, breedSpecRows: configured.breedSpecRows.slice(0,1) });
assert.equal(result.total, null, 'Partial period cannot be a complete total');
assert.ok(result.problems[0].includes('daily feed standards'));
result = build({ ...input, currentMaleCount: 0, currentFemaleCount: 0 });
assert.equal(result.total, 0);
assert.deepEqual(result.problems, []);
console.log('Projection input tests passed: missing breeds, one-sex omission, missing daily standards and empty flock.');
